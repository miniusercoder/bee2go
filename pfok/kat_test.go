package pfok

import (
	"bytes"
	"encoding/hex"
	"testing"
)

func rev(t *testing.T, s string) []byte {
	t.Helper()
	b, e := hex.DecodeString(s)
	if e != nil {
		t.Fatal(e)
	}
	for i, j := 0, len(b)-1; i < j; i, j = i+1, j-1 {
		b[i], b[j] = b[j], b[i]
	}
	return b
}
func TestUpstreamAgreement(t *testing.T) {
	p, _, e := Standard("test")
	if e != nil {
		t.Fatal(e)
	}
	a := rev(t, "011D4665B357DB361D106E32E353CD534B")
	b := rev(t, "0739539C2AE25B53A05C8D16A14351D8EA86A1DD1893E08EE4A266F970E0243F8DF27F738F64E99E262E337792E5DD847CF2A83362C6EC3C024E47313AA49A1E0A2E637AD35E31EB5F034D889B666701")
	want := rev(t, "777BB35E950D3080C1E896BE4172DBD061423D3BFEF78F15E3F7A7F2FF7A242B")
	got, e := p.DH(a, b)
	if e != nil || !bytes.Equal(got, want) {
		t.Fatalf("DH %x: %v", got, e)
	}
	a = rev(t, "0078E7101B4A8F421D2AF5740D6ED27680")
	a1 := rev(t, "0127E33C0D7595566570936FEF0AA53A24")
	b = rev(t, "193E5E1E0839091BC7ABBDD09E8D22988812D37EDEB39E077130A244888BE1A753337AB5743C898D1CFC94743081344816AF5189A4E84D5B6EA310F72534D2E5E531B579CEA862EAB0251A3C20F0EC1D")
	b1 := rev(t, "0947264BEFA107E99616F347B6A05C62D7F5F26804D848FC4A7D81915F4546DD22949C07131D84F8B5A73A60ED61BC6E158E9B83F38C1EE6AD97F2BF771AA4FFB10A38298498D943995697FD0F65284C")
	want = rev(t, "EA92D5BCEC18BB44514E096748DB3E21D6E7B9C97D604699BEA7D3B96C87E18B")
	got, e = p.MTI(a, a1, b, b1)
	if e != nil || !bytes.Equal(got, want) {
		t.Fatalf("MTI %x: %v", got, e)
	}
}
